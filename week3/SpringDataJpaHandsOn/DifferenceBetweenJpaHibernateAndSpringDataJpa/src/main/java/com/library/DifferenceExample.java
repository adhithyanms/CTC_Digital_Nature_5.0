package com.library;

public class DifferenceExample {
    public static void main(String[] args) {
        System.out.println("JPA, Hibernate, and Spring Data JPA");
        System.out.println("JPA is a specification that defines how Java objects are persisted.");
        System.out.println("Hibernate is an ORM implementation of JPA.");
        System.out.println("Spring Data JPA is an abstraction that reduces boilerplate code on top of JPA providers.");
        System.out.println();
        System.out.println("Key difference summary:");
        System.out.println("JPA: standard API/specification.");
        System.out.println("Hibernate: ORM framework and JPA implementation.");
        System.out.println("Spring Data JPA: repository abstraction over JPA/Hibernate.");
    }
}
